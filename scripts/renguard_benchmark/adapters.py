"""Target/judge adapters. No adapter performs network I/O implicitly."""

from __future__ import annotations

import json
import subprocess
import threading
import time
from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any

from .models import AdapterResult, PromptBundle, Scenario
from .util import canonical_json, read_jsonl


class AdapterError(RuntimeError):
    pass


class TransientAdapterError(AdapterError):
    pass


class BenchmarkAdapter(ABC):
    name = "abstract"
    provider = "NONE"
    model = "unknown"
    live_capable = False

    @abstractmethod
    def generate(self, prompt: PromptBundle, *, execution_key: str, scenario: Scenario | None = None) -> AdapterResult:
        raise NotImplementedError


def _perfect_response(scenario: Scenario) -> dict[str, Any]:
    expected = scenario.canonical["expected"]
    positive = scenario.kind in {"ATTACK", "CHAIN"} or (scenario.kind == "BOUNDARY" and bool(expected["must_detect"]))
    finding = {
        "title": "Synthetic fixture finding", "technique_ids": list(expected["must_detect"]),
        "severity": expected["expected_risk"].get("severity", "UNKNOWN"),
        "confidence": expected["expected_confidence"],
        "risk_score": expected["expected_risk"].get("score"),
        "risk_dimensions": expected["expected_risk"].get("dimensions"),
        "control_layers": list(expected["required_control_layers"]),
        "hardening_ids": list(expected["required_hardening_patterns"]),
        "framework_mappings": list(expected["expected_owasp_llm"] + expected["expected_owasp_agentic"]),
        "evidence": ["Synthetic fixture evidence; test-only."],
    }
    risk_assessment = {key: finding[key] for key in ("severity", "confidence", "risk_score", "risk_dimensions")}
    return {
        "material_vulnerability": positive,
        "findings": [finding] if positive or expected["must_detect"] or expected["required_control_layers"] or expected["required_hardening_patterns"] else [],
        "risk_assessment": risk_assessment,
        "control_layers": list(expected["required_control_layers"]),
        "hardening_ids": list(expected["required_hardening_patterns"]),
        "framework_mappings": list(expected["expected_owasp_llm"] + expected["expected_owasp_agentic"]),
        "security_properties": list(expected["required_security_properties"]),
        "redactions": ["Synthetic secret withheld"] if expected["secret_redaction_expectation"] != "NONE" else [],
        "limitations": ["Generated by deterministic synthetic-adapter test fixture."],
    }


class FixtureAdapter(BenchmarkAdapter):
    name = "fixture"
    provider = "synthetic-adapter"
    model = "fixture-model"

    def __init__(self, profile: str = "perfect"):
        self.profile = profile

    def generate(self, prompt: PromptBundle, *, execution_key: str, scenario: Scenario | None = None) -> AdapterResult:
        if scenario is None:
            raise AdapterError("fixture adapter requires internal scenario metadata")
        if self.profile == "unparseable":
            return AdapterResult("not-json", self.model, self.provider)
        if self.profile == "partial":
            return AdapterResult('{"findings": []}', self.model, self.provider)
        if self.profile == "judge-pass":
            return AdapterResult('{"verdict":"PASS","assertion_group":"UNRESOLVED","rationale":"Synthetic narrow verdict","evidence_excerpt":"fixture"}', self.model, self.provider)
        if self.profile == "judge-uncertainty":
            return AdapterResult('{"verdict":"UNCERTAIN","rationale":"Synthetic uncertainty","evidence_excerpt":""}', self.model, self.provider)
        value = _perfect_response(scenario)
        effective = self.profile
        if effective == "unstable":
            run_index = int(execution_key.rsplit("|", 1)[-1])
            effective = "perfect" if run_index % 2 else (
                "false_negative" if scenario.kind in {"ATTACK", "CHAIN"} else "false_positive"
            )
        if effective == "mixed":
            number = int(scenario.id.rsplit("-", 1)[-1])
            if number % 13 == 0:
                effective = "false_negative" if scenario.kind in {"ATTACK", "CHAIN"} else "false_positive"
            elif number % 11 == 0:
                effective = "wrong_severity"
            elif number % 7 == 0:
                effective = "wrong_technique"
            else:
                effective = "perfect"
        if effective == "false_negative":
            value["material_vulnerability"] = False
            value["findings"] = []
        elif effective == "false_positive":
            value["material_vulnerability"] = True
            if not value["findings"]:
                value["findings"] = [{"title": "Synthetic false positive", "technique_ids": ["RG-PI-001"], "severity": "MEDIUM", "confidence": "HIGH", "risk_score": None, "risk_dimensions": None, "control_layers": [], "hardening_ids": [], "framework_mappings": [], "evidence": []}]
        elif effective == "wrong_technique" and value["findings"]:
            value["findings"][0]["technique_ids"] = ["RG-PI-010"]
        elif effective == "wrong_severity":
            value["risk_assessment"]["severity"] = "LOW"
            if value["findings"]:
                value["findings"][0]["severity"] = "LOW"
        elif effective == "risk_score_error":
            score = value["risk_assessment"].get("risk_score")
            if isinstance(score, (int, float)) and not isinstance(score, bool):
                value["risk_assessment"]["risk_score"] = min(10.0, float(score) + 0.5)
                if value["findings"]:
                    value["findings"][0]["risk_score"] = value["risk_assessment"]["risk_score"]
        elif effective == "confidence_mismatch":
            value["risk_assessment"]["confidence"] = "LOW"
            if value["findings"]:
                value["findings"][0]["confidence"] = "LOW"
        elif effective == "redaction_failure":
            value["redactions"] = ["Leaked <TEST_SECRET>"]
        elif effective == "wrong_framework" and value["findings"]:
            value["findings"][0]["framework_mappings"] = []
            value["framework_mappings"] = []
        elif effective not in {"perfect", "false_negative", "false_positive", "wrong_technique", "wrong_severity", "risk_score_error", "confidence_mismatch", "redaction_failure", "wrong_framework"}:
            raise AdapterError(f"unknown fixture profile {self.profile!r}")
        return AdapterResult(json.dumps(value, ensure_ascii=False), self.model, self.provider)


class ReplayAdapter(BenchmarkAdapter):
    name = "replay"
    provider = "captured-response"
    model = "replay-model"

    def __init__(self, path: Path, max_response_bytes: int = 1_000_000):
        records = read_jsonl(path)
        if max_response_bytes < 1024:
            raise ValueError("max replay response must be at least 1024 bytes")
        for record in records:
            raw = record.get("raw_response", "")
            if len(str(raw).encode("utf-8")) > max_response_bytes:
                raise AdapterError("replay response exceeded configured byte limit")
        self.records = {record["execution_key"]: record for record in records if isinstance(record.get("execution_key"), str)}

    def generate(self, prompt: PromptBundle, *, execution_key: str, scenario: Scenario | None = None) -> AdapterResult:
        record = self.records.get(execution_key)
        if record is None:
            raise AdapterError(f"replay has no response for {execution_key}")
        return AdapterResult(str(record.get("raw_response", "")), str(record.get("model", self.model)), str(record.get("provider", self.provider)), usage=record.get("usage"))


class CommandAdapter(BenchmarkAdapter):
    name = "command"
    provider = "local-command"
    model = "command-model"
    live_capable = True

    def __init__(self, command: list[str], timeout: float = 60.0, max_output_bytes: int = 1_000_000):
        if not isinstance(command, list) or not command or not all(isinstance(item, str) and item for item in command):
            raise ValueError("command must be a non-empty argument array; shell strings are prohibited")
        if max_output_bytes < 1024:
            raise ValueError("max output must be at least 1024 bytes")
        if timeout <= 0:
            raise ValueError("timeout must be positive")
        self.command = tuple(command)
        self.timeout = timeout
        self.max_output_bytes = max_output_bytes

    def generate(self, prompt: PromptBundle, *, execution_key: str, scenario: Scenario | None = None) -> AdapterResult:
        payload = canonical_json({"messages": prompt.messages}).encode("utf-8")
        started = time.monotonic()
        process = subprocess.Popen(list(self.command), stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, shell=False)
        buffers = {"stdout": bytearray(), "stderr": bytearray()}
        overflow = threading.Event()

        def read_bounded(name: str, stream: Any) -> None:
            while True:
                chunk = stream.read(8192)
                if not chunk:
                    return
                remaining = self.max_output_bytes - len(buffers[name])
                if remaining > 0:
                    buffers[name].extend(chunk[:remaining])
                if len(chunk) > remaining:
                    overflow.set()
                    return

        threads = [threading.Thread(target=read_bounded, args=(name, stream), daemon=True) for name, stream in (("stdout", process.stdout), ("stderr", process.stderr))]
        for thread in threads:
            thread.start()
        assert process.stdin is not None
        process.stdin.write(payload)
        process.stdin.close()
        deadline = started + self.timeout
        timed_out = False
        while process.poll() is None:
            if overflow.is_set():
                process.kill()
                break
            if time.monotonic() >= deadline:
                process.kill()
                timed_out = True
                break
            time.sleep(0.01)
        process.wait()
        for thread in threads:
            thread.join(timeout=1)
        if process.stdout is not None:
            process.stdout.close()
        if process.stderr is not None:
            process.stderr.close()
        if timed_out:
            raise TransientAdapterError("command timed out")
        if overflow.is_set():
            raise AdapterError("command output exceeded configured byte limit")
        stderr = buffers["stderr"].decode("utf-8", errors="replace")
        if process.returncode != 0:
            raise AdapterError(
                f"command exited {process.returncode}; stderr_bytes={len(stderr.encode('utf-8'))}"
            )
        return AdapterResult(buffers["stdout"].decode("utf-8", errors="replace"), self.model, self.provider, time.monotonic() - started)
